#!/usr/bin/env php
<?php

/**
 * Generates docs/cli-reference.md from the command definitions, so the reference cannot drift from the
 * code. Run after changing any command:  php bin/cli-reference.php > docs/cli-reference.md
 * CI regenerates it and fails when the committed page differs.
 */

declare(strict_types=1);

use Remediate\Command\CommandProvider;
use Remediate\Engine\Advisory\Db\DatabaseLocator;
use Remediate\Engine\Plan\Plan;
use Symfony\Component\Console\Command\Command;
use Symfony\Component\Console\Input\InputOption;

require dirname(__DIR__) . '/vendor/autoload.php';

$out = [];
$out[] = '<!-- Generated by bin/cli-reference.php; do not edit by hand. -->';
$out[] = '# CLI reference';
$out[] = '';
$out[] = 'All commands are Composer plugin commands and accept Composer\'s global options as well (`-v`, `-q`, `--no-ansi`, `-d/--working-dir`, `--no-plugins`, and so on). `composer <command> --help` prints the same information in the terminal.';
$out[] = '';

/** @var list<Command> $commands */
$commands = (new CommandProvider())->getCommands();
foreach ($commands as $command) {
    $out[] = '## `composer ' . $command->getName() . '`';
    $out[] = '';
    $aliases = $command->getAliases();
    if ($aliases !== []) {
        $out[] = 'Aliases: ' . implode(', ', array_map(static fn (string $a): string => '`' . $a . '`', $aliases));
        $out[] = '';
    }
    $out[] = htmlspecialchars($command->getDescription(), ENT_NOQUOTES);
    $out[] = '';
    $help = htmlspecialchars(trim(str_replace(['<info>', '</info>', '<comment>', '</comment>'], '`', $command->getHelp())), ENT_NOQUOTES);
    if ($help !== '') {
        $out[] = $help;
        $out[] = '';
    }
    $options = $command->getDefinition()->getOptions();
    if ($options !== []) {
        $out[] = '| Option | Value | Description |';
        $out[] = '|---|---|---|';
        foreach ($options as $option) {
            $name = '`--' . $option->getName() . '`' . ($option->getShortcut() !== null ? ', `-' . $option->getShortcut() . '`' : '');
            $value = match (true) {
                $option->isArray() => 'repeatable',
                $option->isValueRequired() => 'required',
                $option->isValueOptional() => 'optional',
                default => 'flag',
            };
            $default = $option->getDefault();
            if ($option->acceptValue() && is_scalar($default) && $default !== '' && $default !== false) {
                $value .= ', default `' . $default . '`';
            }
            $out[] = sprintf('| %s | %s | %s |', $name, $value, htmlspecialchars(str_replace('|', '\\|', $option->getDescription()), ENT_NOQUOTES));
        }
        $out[] = '';
    }
}

$out[] = '## Exit codes';
$out[] = '';
$out[] = '| Code | Meaning |';
$out[] = '|---|---|';
foreach ([
    Plan::EXIT_CLEAN => 'No known vulnerabilities in the locked dependencies',
    Plan::EXIT_REMEDIATION_AVAILABLE => 'Vulnerabilities found and a verified remediation exists for every one',
    Plan::EXIT_NO_REMEDIATION => 'At least one vulnerability has no verified remediation',
    Plan::EXIT_ERROR => 'Tool or configuration error (no lock file, unknown option, unwritable output)',
    Plan::EXIT_ADVISORIES_UNAVAILABLE => 'Advisory data could not be obtained (network, missing or invalid database or snapshot); also used by `remediate:db-build` when a source fails',
    Plan::EXIT_SOLVER_FAILURE => 'Package metadata could not be fetched during solving (network), so no candidate could be verified',
] as $code => $meaning) {
    $out[] = sprintf('| `%d` | %s |', $code, $meaning);
}
$out[] = '';
$out[] = '## Environment variables';
$out[] = '';
$out[] = '| Variable | Effect |';
$out[] = '|---|---|';
$out[] = '| `' . DatabaseLocator::ENV . '` | Path or URL of the advisory database, used when `--database-location` is not given |';
$out[] = '| `COMPOSER_DISABLE_NETWORK` | Set to `1` by `--offline`; may also be set by hand to make every Composer call refuse the network |';
$out[] = '| `COMPOSER_CACHE_DIR`, `COMPOSER_HOME` | Composer\'s own; the advisory database default output and URL downloads live under `<cache-dir>/remediate/` |';
$out[] = '';
$out[] = '## composer.json keys';
$out[] = '';
$out[] = '| Key | Effect |';
$out[] = '|---|---|';
$out[] = '| `extra.remediate.database` | Default advisory database location for this project (path or URL), lowest precedence after the option and the environment variable |';
$out[] = '| `config.audit.ignore` | Advisory ids (list, or map of id to reason) that are ignored, as `composer audit` does (Composer 2.x) |';
$out[] = '| `config.policy.advisories.ignore`, `config.policy.advisories.ignore-id` | Same, in the policy block introduced by Composer 2.10 |';
$out[] = '| `config.platform` | Honoured by candidate solves exactly as by `composer update`; determines whether a fix requiring a newer PHP is reachable |';
$out[] = '';
$out[] = '## Report formats';
$out[] = '';
$out[] = '`--format` selects what goes to standard output (`text` by default, or `html`, `json`, `none`). `--output=<file>` writes a report file, format inferred from the extension (`.html`, `.json`, `.txt`) or given as a prefix (`json:path`); it may be repeated. See [How it works](how-it-works.md#8-output) for the JSON structure.';
$out[] = '';

echo implode("\n", $out);
