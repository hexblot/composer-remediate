#!/usr/bin/env php
<?php

/**
 * Generates docs/case-studies.md from the fixture corpus: every real historical project under
 * tests/Fixture (the synthetic fixture is skipped) contributes its provenance and reasoning
 * (README.md) and the planner's actual result (reports/report.json). Run after adding or rebuilding
 * a fixture:  php bin/case-studies.php > docs/case-studies.md
 * CI regenerates it and fails when the committed page differs.
 */

declare(strict_types=1);

$root = dirname(__DIR__);
$fixtureRoot = $root . '/tests/Fixture';
$repo = 'https://github.com/hexblot/composer-remediate/blob/main/tests/Fixture';

/** @return array<string, mixed> */
function readJson(string $path): array
{
    $decoded = json_decode((string) file_get_contents($path), true, 512, JSON_THROW_ON_ERROR);
    if (!is_array($decoded)) {
        throw new RuntimeException("$path is not a JSON object");
    }

    /** @var array<string, mixed> $decoded */
    return $decoded;
}

/** The fixture README without its title, headings demoted so they nest under the case-study heading. */
function readmeBody(string $path): string
{
    $lines = explode("\n", rtrim((string) file_get_contents($path)));
    $body = [];
    foreach ($lines as $index => $line) {
        if ($index === 0 && str_starts_with($line, '# ')) {
            continue;
        }
        if (preg_match('{^(#{1,4}) (.*)$}', $line, $m) === 1) {
            $line = str_repeat('#', min(6, strlen($m[1]) + 2)) . ' ' . $m[2];
        }
        $body[] = $line;
    }

    return trim(implode("\n", $body));
}

/** @param array<string, mixed> $finding */
function advisoryIds(array $finding): string
{
    $ids = [];
    foreach (is_array($finding['advisories'] ?? null) ? $finding['advisories'] : [] as $advisory) {
        if (is_array($advisory)) {
            $ids[] = is_string($advisory['cve'] ?? null) ? $advisory['cve'] : (string) ($advisory['id'] ?? '?');
        }
    }

    return implode(', ', $ids);
}

function cell(string $text): string
{
    return str_replace(['|', "\n"], ['\|', ' '], $text);
}

/** A command inside a table cell: raw <code> with the pipe as an entity, since Markdown's \| escape is not honoured inside code spans. */
function code(string $command): string
{
    return '<code>' . str_replace('|', '&#124;', htmlspecialchars($command, ENT_QUOTES | ENT_HTML5)) . '</code>';
}

$dirs = glob($fixtureRoot . '/*/expected.json') ?: [];
sort($dirs);

$out = [];
$out[] = '<!-- Generated by bin/case-studies.php from tests/Fixture; do not edit by hand. -->';
$out[] = '# Case studies';
$out[] = '';
$out[] = 'Every case below is a real project at a real commit, frozen with the package metadata and advisories';
$out[] = 'that existed at the time, so the result reproduces exactly (see [Test fixtures](fixtures.md) for the';
$out[] = 'format). Each shows the situation a developer faced, what a competent human chose, and what';
$out[] = '`composer remediate` recommends. The stored console, JSON, HTML and SARIF reports are the tool\'s';
$out[] = 'actual output for that fixture, generated by `bin/run-fixture.php --write-reports`. These are the';
$out[] = 'same fixtures the test suite asserts on, so a case study that stopped being true would fail CI.';
$out[] = '';

$summary = [];
$sections = [];
foreach ($dirs as $expectedPath) {
    $dir = dirname($expectedPath);
    $name = basename($dir);
    if (str_starts_with($name, 'synthetic-')) {
        continue;
    }
    $expected = readJson($expectedPath);
    $reportPath = $dir . '/reports/report.json';
    if (!is_file($reportPath)) {
        fwrite(STDERR, "warning: $name has no reports/report.json; run bin/run-fixture.php $name --write-reports\n");
        continue;
    }
    $report = readJson($reportPath);
    /** @var array<string, mixed> $reportSummary */
    $reportSummary = is_array($report['summary'] ?? null) ? $report['summary'] : [];
    /** @var list<array<string, mixed>> $findings */
    $findings = array_values(array_filter(is_array($report['findings'] ?? null) ? $report['findings'] : [], 'is_array'));

    $advisories = (int) ($reportSummary['advisories'] ?? 0);
    $packages = count($findings);
    $withFix = (int) ($reportSummary['packages_with_fix'] ?? 0);
    $combined = is_string($reportSummary['combined_command'] ?? null) ? $reportSummary['combined_command'] : null;
    $combinedFixes = $reportSummary['combined_fixes'] ?? null;
    $combinedTotal = $reportSummary['combined_total'] ?? null;
    $outcome = match (true) {
        $packages === 0 => 'clean',
        $withFix === 0 => 'no verified fix',
        $withFix === $packages => 'all fixable',
        default => sprintf('%d of %d packages fixable', $withFix, $packages),
    };
    $summary[] = sprintf('| [%s](#%s) | %d | %d | %s | %s |', $name, $name, $advisories, $packages, $outcome, $combined !== null ? code($combined) : 'per-package commands or none');

    $s = [];
    $s[] = '## ' . $name;
    $s[] = '';
    $description = is_string($expected['description'] ?? null) ? $expected['description'] : '';
    if ($description !== '') {
        $s[] = '*' . $description . '*';
        $s[] = '';
    }
    if (is_file($dir . '/README.md')) {
        $s[] = readmeBody($dir . '/README.md');
        $s[] = '';
    }
    $s[] = '#### Planner result';
    $s[] = '';
    $s[] = sprintf('%d advisor%s on %d package%s; %d package%s with a verified fix.', $advisories, $advisories === 1 ? 'y' : 'ies', $packages, $packages === 1 ? '' : 's', $withFix, $withFix === 1 ? '' : 's');
    $s[] = '';
    $s[] = '| Package | Advisories | Recommended command | Changes | Outcome |';
    $s[] = '|---|---|---|---|---|';
    foreach ($findings as $finding) {
        /** @var array<string, mixed> $remediation */
        $remediation = is_array($finding['remediation'] ?? null) ? $finding['remediation'] : [];
        $command = is_string($remediation['command'] ?? null) ? code($remediation['command']) : '';
        $changes = is_array($remediation['summary'] ?? null) ? (string) ($remediation['summary']['total'] ?? '') : '';
        $status = ($remediation['status'] ?? '') === 'verified' ? 'verified' : (string) ($remediation['outcome'] ?? 'none');
        $s[] = sprintf('| %s %s%s | %s | %s | %s | %s |', cell((string) ($finding['package'] ?? '')), cell((string) ($finding['version'] ?? '')), ($finding['dev'] ?? false) === true ? ' (dev)' : '', cell(advisoryIds($finding)), $command, $changes, $status);
    }
    $s[] = '';
    if ($combined !== null) {
        $s[] = sprintf('Combined command (%s of %s findings): `%s`', (string) $combinedFixes, (string) $combinedTotal, $combined);
        $s[] = '';
    }
    $reports = [];
    foreach (['report.md' => 'console', 'report.json' => 'JSON', 'report.html' => 'HTML', 'report.sarif' => 'SARIF', 'report.cdx.json' => 'CycloneDX', 'gl-dependency-scanning-report.json' => 'GitLab'] as $file => $label) {
        if (is_file($dir . '/reports/' . $file)) {
            $reports[] = sprintf('[%s](%s/%s/reports/%s)', $label, $repo, $name, $file);
        }
    }
    $s[] = sprintf('Stored reports: %s. Fixture: [%s](%s/%s).', implode(', ', $reports), $name, $repo, $name);
    $s[] = '';
    $sections[] = implode("\n", $s);
}

$out[] = '| Case | Advisories | Packages | Outcome | Combined command |';
$out[] = '|---|---|---|---|---|';
array_push($out, ...$summary);
$out[] = '';
array_push($out, ...$sections);

echo implode("\n", $out), "\n";
